/**
 * Метки в строке сотрудника → LBX.
 * Ловим "ЛАНЧ БОКС" в скобках, "ланчбокс", "lunch box", "лбх", "lbx",
 * "диета", "diet" — в любом регистре и раскладке.
 *
 * Пример: "Aitkali Kiyekpayev (ЛАНЧ БОКС)" → LBX.
 */
const LUNCHBOX_PATTERNS = [
  /ланч\s*бокс/i,
  /ланчбокс/i,
  /lunch\s*box/i,
  /lunchbox/i,
  /\blbx\b/i,
  /\bлбх\b/i,
  /диет/i,
  /diet/i,
  /ланч/i,
];

export function resolveLocation(raw) {
  if (!raw) return { key: 'UNKNOWN', raw: null };
  const s = String(raw);
  for (const { key, patterns } of LOCATION_MAP) {
    if (patterns.some((re) => re.test(s))) return { key, raw: s };
  }
  return { key: 'UNKNOWN', raw: s };
}

export function isLunchbox(rowText) {
  const s = String(rowText ?? '');
  return LUNCHBOX_PATTERNS.some((re) => re.test(s));
}